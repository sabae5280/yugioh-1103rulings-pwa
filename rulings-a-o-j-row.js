// 既存カードがある場合は概要を保持し、重複Q&Aは原文の日付なし表記へ統合します。
(function () {
  const norm = (value) => String(value || "").normalize("NFKC")
    .replace(/\(\d{2}\/\d{2}\/\d{2}\)/g, "")
    .replace(/[\s　・･•－―—–ー_＿《》「」『』【】]/g, "")
    .toLowerCase();
  for (const source of window.A_O_J_RULINGS || []) {
    const existing = window.RULINGS.find((item) => norm(item.name) === norm(source.name));
    if (!existing) {
      window.RULINGS.push(source);
      continue;
    }
    for (const key of ["reading", "type", "spellType", "trapType", "cardClass", "monsterTags", "environments", "coverImage", "coverImageAlt"]) {
      if (source[key] !== undefined) existing[key] = source[key];
    }
    if (!existing.image && source.image) existing.image = source.image;
    if (!existing.overview && source.overview) existing.overview = source.overview;
    if (source.related?.length) existing.related = [...new Set([...(existing.related || []), ...source.related])];
    existing.qa ||= [];
    for (const qa of source.qa || []) {
      const prior = existing.qa.find((entry) => norm(entry.question) === norm(qa.question));
      if (prior) Object.assign(prior, qa);
      else existing.qa.push(qa);
    }
  }
})();
